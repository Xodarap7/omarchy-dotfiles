-- Описания, которые Omarchy собирает из чисел (рабочие столы, панели, группы).
M.patterns = {
  { "^Switch to workspace (%d+)$", "Переключиться на рабочий стол %1" },
  { "^Move window silently to workspace (%d+)$", "Переместить окно без фокуса на рабочий стол %1" },
  { "^Move window to workspace (%d+)$", "Переместить окно на рабочий стол %1" },
  { "^Bar panel (%d+)$", "Панель бара %1" },
  { "^Switch to group window (%d+)$", "Окно группы %1" },
}

function M.translate(description)
  if type(description) ~= "string" or description == "" then
    return description
  end

  local exact = M.exact[description]
  if exact then
    return exact
  end

  for _, rule in ipairs(M.patterns) do
    if description:match(rule[1]) then
      return (description:gsub(rule[1], rule[2]))
    end
  end

  return description
end

return M
